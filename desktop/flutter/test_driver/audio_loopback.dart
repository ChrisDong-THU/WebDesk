// Explicit test entrypoint; never included by build-flutter.ps1.
// Tests the real Windows loopback source and Opus transport without the service.
import 'dart:convert';
import 'dart:io';
import 'dart:math';
import 'dart:typed_data';
import 'package:flutter/widgets.dart';
import 'package:flutter_webrtc/flutter_webrtc.dart';
import 'package:webdesk/native/system_audio.dart';
import 'package:webdesk/session/peer_connection.dart';

void check(bool condition, String message) {
  if (!condition) throw StateError(message);
}

Future<void> main(List<String> args) async {
  WidgetsFlutterBinding.ensureInitialized();
  final out = Directory(args.single)..createSync(recursive: true);
  final audio = SystemAudio();
  RTCPeerConnection? sender, receiver;
  MediaStream? desktop;
  final results = <String, dynamic>{};
  Future<void> checkMicrophone(String stage) async {
    final probe = await Process.run('${out.path}/audio-session-probe.exe', [
      '$pid',
    ]);
    check(probe.exitCode == 0, 'Microphone probe failed: ${probe.stderr}');
    final state = jsonDecode(probe.stdout as String) as Map<String, dynamic>;
    results['microphone.$stage'] = state;
    check(
      state['activeCaptureSessions'] == 0 && state['openCaptureSessions'] == 0,
      'WebDesk opened a microphone capture session ($stage)',
    );
  }

  int code = 1;
  try {
    sender = await createPeerConnection({'iceServers': []});
    receiver = await createPeerConnection({'iceServers': []});
    final a = sender, b = receiver;
    final pendingA = <RTCIceCandidate>[], pendingB = <RTCIceCandidate>[];
    bool remoteA = false, remoteB = false;
    a.onIceCandidate = (c) {
      if (remoteB) {
        b.addCandidate(c);
      } else {
        pendingB.add(c);
      }
    };
    b.onIceCandidate = (c) {
      if (remoteA) {
        a.addCandidate(c);
      } else {
        pendingA.add(c);
      }
    };
    final sources = await desktopCapturer.getSources(
      types: [SourceType.Screen],
    );
    desktop = await navigator.mediaDevices.getDisplayMedia({
      'audio': false,
      'video': {
        'deviceId': {'exact': sources.first.id},
        'mandatory': {'frameRate': 10.0},
      },
    });
    final videoSender = await a.addTrack(
      desktop.getVideoTracks().single,
      desktop,
    );
    final stream = await audio.create();
    await a.addTrack(stream.getAudioTracks().single, desktop);
    final offer = await a.createOffer();
    await a.setLocalDescription(offer);
    await b.setRemoteDescription(offer);
    remoteB = true;
    for (final c in pendingB) {
      await b.addCandidate(c);
    }
    final answer = await b.createAnswer();
    await b.setLocalDescription(answer);
    await a.setRemoteDescription(answer);
    remoteA = true;
    for (final c in pendingA) {
      await a.addCandidate(c);
    }
    for (
      var i = 0;
      i < 100 &&
          a.connectionState !=
              RTCPeerConnectionState.RTCPeerConnectionStateConnected;
      i++
    ) {
      await Future<void>.delayed(const Duration(milliseconds: 100));
    }
    check(
      a.connectionState ==
          RTCPeerConnectionState.RTCPeerConnectionStateConnected,
      'ICE did not connect',
    );
    Future<Map<String, dynamic>> sample() async {
      final stats = await b.getStats();
      return Map<String, dynamic>.from(
        stats
                .where(
                  (r) =>
                      r.type == 'inbound-rtp' &&
                      (r.values['kind'] == 'audio' ||
                          r.values['mediaType'] == 'audio'),
                )
                .firstOrNull
                ?.values ??
            {},
      );
    }

    Future<Map<String, dynamic>> settled() async {
      await Future<void>.delayed(const Duration(seconds: 2));
      return sample();
    }

    results['initialOff'] = await settled();
    await checkMicrophone('connectedSoundOff');
    // Known low-volume tone is generated by a separate process, so the native
    // source's exclusion of our own process cannot mask a non-working capture.
    final data = ByteData(44 + 48000 * 2 * 20);
    void tag(int offset, String text) {
      for (var i = 0; i < text.length; i++) {
        data.setUint8(offset + i, text.codeUnitAt(i));
      }
    }

    tag(0, 'RIFF');
    data.setUint32(4, data.lengthInBytes - 8, Endian.little);
    tag(8, 'WAVE');
    tag(12, 'fmt ');
    data.setUint32(16, 16, Endian.little);
    data.setUint16(20, 1, Endian.little);
    data.setUint16(22, 1, Endian.little);
    data.setUint32(24, 48000, Endian.little);
    data.setUint32(28, 96000, Endian.little);
    data.setUint16(32, 2, Endian.little);
    data.setUint16(34, 16, Endian.little);
    tag(36, 'data');
    data.setUint32(40, data.lengthInBytes - 44, Endian.little);
    for (var i = 0; i < 48000 * 20; i++) {
      data.setInt16(
        44 + i * 2,
        (sin(i * 2 * pi * 440 / 48000) * 600).round(),
        Endian.little,
      );
    }
    File('${out.path}/tone.wav').writeAsBytesSync(data.buffer.asUint8List());
    // The runner plays this from a sibling process. WASAPI intentionally
    // excludes this process AND its descendants, preventing feedback.
    File('${out.path}/tone-ready').writeAsStringSync('ready');
    for (
      var i = 0;
      i < 100 && !File('${out.path}/tone-started').existsSync();
      i++
    ) {
      await Future<void>.delayed(const Duration(milliseconds: 100));
    }
    check(
      File('${out.path}/tone-started').existsSync(),
      'External tone was not started',
    );
    await audio.setEnabled(true);
    final first = await settled(), second = await settled();
    results['enabled'] = [first, second];
    await checkMicrophone('soundOn');
    check(
      (second['totalAudioEnergy'] as num? ?? 0) -
              (first['totalAudioEnergy'] as num? ?? 0) >
          0.000001,
      'No decoded system audio energy',
    );
    // Retiring the video capture used to stop the plugin's shared loopback.
    // Our independent source must keep producing audio through this operation.
    await videoSender.replaceTrack(null);
    for (final track in desktop.getTracks()) {
      await track.stop();
    }
    await desktop.dispose();
    desktop = null;
    final afterVideo = await settled();
    results['afterVideoStopped'] = afterVideo;
    check(
      (afterVideo['totalAudioEnergy'] as num) >
          (second['totalAudioEnergy'] as num),
      'Video lifecycle stopped audio',
    );
    await audio.setEnabled(false);
    final off1 = await settled(), off2 = await settled();
    results['disabled'] = [off1, off2];
    await checkMicrophone('soundOff');
    check(
      (off2['totalAudioEnergy'] as num) - (off1['totalAudioEnergy'] as num) <
          0.00001,
      'Audio continued after disabling',
    );
    await audio.setEnabled(true);
    final again = await settled();
    results['reenabled'] = again;
    await checkMicrophone('soundReenabled');
    check(
      (again['totalAudioEnergy'] as num) > (off2['totalAudioEnergy'] as num),
      'Audio did not resume',
    );
    results['ok'] = true;
    code = 0;
  } catch (error, stack) {
    results.addAll({'ok': false, 'error': '$error', 'stack': '$stack'});
  } finally {
    await audio.close();
    await closePeerConnection(sender);
    await closePeerConnection(receiver);
    if (desktop != null) {
      for (final track in desktop.getTracks()) {
        await track.stop();
      }
      await desktop.dispose();
    }
    try {
      await checkMicrophone('disconnected');
    } catch (error) {
      results.addAll({'ok': false, 'error': '$error'});
      code = 1;
    }
    File(
      '${out.path}/result.json',
    ).writeAsStringSync(const JsonEncoder.withIndent('  ').convert(results));
    exit(code);
  }
}
